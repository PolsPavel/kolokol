/**
 * Устаревший скрипт.
 *
 * Ранее он создавал таблицу User только с частью полей,
 * тогда как актуальная модель User находится в schema.prisma.
 *
 * Не создаём и не изменяем базу этим скриптом.
 * Для управления схемой используй Prisma после резервного
 * копирования базы и проверки DATABASE_URL.
 */

function main(): never {
  console.error(
    [
      "❌ prisma/init-db.ts отключён.",
      "Он создаёт неполную схему, несовместимую с текущей моделью User.",
      "",
      "Проверь DATABASE_URL и prisma/schema.prisma.",
      "Перед изменением схемы сделай резервную копию базы.",
      "Затем используй согласованный процесс управления схемой Prisma.",
    ].join("\n")
  );

  process.exitCode = 1;
  throw new Error("Устаревшая инициализация базы отключена.");
}

main();